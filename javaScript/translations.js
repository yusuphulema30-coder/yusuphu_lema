/**
 * Get a single translation
 * 
 * Usage: getTranslation('hero-title', 'en')
 * Returns: The translated text
 * 
 * @param {string} key - The translation key
 * @param {string} language - 'en' or 'sw'
 * @returns {string} The translated text or key if not found
 */
function getTranslation(key, language) {
    // Check if key exists in translations
    if (translations[key]) {
        // Return translation in requested language, fallback to English
        return translations[key][language] || translations[key]['en'];
    }
    // Return key name if translation not found (helps with debugging)
    console.warn(`Translation key not found: ${key}`);
    return key;
}

/**
 * Translate all elements on the page
 * 
 * Called when user clicks language toggle
 * 
 * @param {string} language - 'en' or 'sw'
 */
function translatePage(language) {
    // Find all elements with data-translate attribute
    const elements = document.querySelectorAll('[data-translate]');
    
    // Loop through each element
    elements.forEach(element => {
        // Get the translation key
        const key = element.getAttribute('data-translate');
        
        // Get the translation
        const translation = getTranslation(key, language);
        
        // Check element type and update accordingly
        if (element.tagName === 'INPUT') {
            // For input fields, update placeholder
            element.placeholder = translation;
        } else if (element.tagName === 'SELECT') {
            // For select options, update all text
            element.textContent = translation;
        } else if (element.tagName === 'TEXTAREA') {
            // For textareas, update placeholder
            element.placeholder = translation;
        } else {
            // For everything else (divs, spans, h1, p, etc), update text
            element.textContent = translation;
        }
    });
    
    // Update toggle button text
    const toggleBtn = document.getElementById('lang-text');
    if (toggleBtn) {
        toggleBtn.textContent = language === 'en' ? 'SWAHILI' : 'ENGLISH';
    }
    
    // Save language preference to browser storage
    localStorage.setItem('preferredLanguage', language);
    
    // Update HTML language attribute for accessibility
    document.documentElement.lang = language;

}

